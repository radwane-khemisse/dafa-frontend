export const products: Product[] = [...unsortedProducts].sort(
  (a, b) => productDisplayOrder.indexOf(a.id) - productDisplayOrder.indexOf(b.id),
);

export function getProductBySlug(slug: string) {
  return products.find((product) => product.slug === slug);
}

export function getProductById(id: Product["id"]) {
  return products.find((product) => product.id === id);
}

export function getCrossSells(productIds: string[]) {
  return products.filter((product) => !productIds.includes(product.id));
}
